/** Text in die gewünschte Sprache bringen (unbekannte Texte bleiben, wie sie sind). */
export function tr(s, lang) {
  if (typeof s !== 'string') return s;
  if (lang === 'sv') {
    if (SV[s] !== undefined) return SV[s];
    const m = s.match(/^(.+) gibt es schon\. Nimm z\.B\. noch den ersten Buchstaben vom Nachnamen dazu\.$/);
    if (m) return `${m[1]} finns redan. Lägg t.ex. till första bokstaven i efternamnet.`;
    return EN[s] ?? s;
  }
  if (lang !== 'en') return s;
  if (EN[s] !== undefined) return EN[s];
  // "… gibt es schon." usw.
  const m = s.match(/^(.+) gibt es schon\. Nimm z\.B\. noch den ersten Buchstaben vom Nachnamen dazu\.$/);
  if (m) return `${m[1]} already exists. Add e.g. the first letter of your surname.`;
  return s;
}
